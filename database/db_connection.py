def _url_limpia(url):
    """Quita parámetros que psycopg no entiende (p. ej. los de Prisma)."""
    partes = urlsplit(url)
    ignorar = {"pgbouncer", "connection_limit", "pool_timeout", "schema"}
    consulta = [(clave, valor) for clave, valor in parse_qsl(partes.query)
                if clave not in ignorar]
    return urlunsplit((partes.scheme, partes.netloc, partes.path,
                       urlencode(consulta), partes.fragment))


class _ConexionPostgres:
    """Adaptador mínimo que imita la API de sqlite3 que usa el proyecto."""

    is_postgres = True

    def __init__(self, url):
        if not _POSTGRES_DISPONIBLE:
            raise RuntimeError(
                "DATABASE_URL está definido pero falta psycopg. "
                "Instala con: pip install \"psycopg[binary]\"")
        # prepare_threshold=None evita sentencias preparadas, necesarias con
        # el pooler (pgBouncer en modo transacción) de Supabase.
        self._conn = psycopg.connect(_url_limpia(url), row_factory=dict_row,
                                     prepare_threshold=None)

    @staticmethod
    def _sql(sql):
        return sql.replace("?", "%s")

    def execute(self, sql, params=()):
        return self._conn.execute(self._sql(sql), params)

    def executemany(self, sql, secuencia):
        with self._conn.cursor() as cursor:
            cursor.executemany(self._sql(sql), secuencia)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()

    def __enter__(self):
        return self

    def __exit__(self, tipo, valor, traza):
        if tipo is None:
            self._conn.commit()
        else:
            self._conn.rollback()
        return False


def es_postgres(conexion):
    """True si la conexión es de PostgreSQL (Supabase)."""
    return getattr(conexion, "is_postgres", False)


def obtener_conexion(ruta=None):
    """Abre una conexión.

    - ``ruta=":memory:"`` o una ruta de archivo -> SQLite (pruebas / local).
    - ``ruta=None`` y ``DATABASE_URL`` definido -> PostgreSQL (Supabase).
    - ``ruta=None`` sin ``DATABASE_URL`` -> SQLite en ``DB_PATH``.
    """
    url = os.environ.get("DATABASE_URL")
    if ruta is None and url:
        return _ConexionPostgres(url)
    if ruta is None:
        ruta = DB_PATH
    conexion = sqlite3.connect(str(ruta))
    conexion.execute("PRAGMA foreign_keys = ON")   # SQLite lo trae apagado
    conexion.row_factory = sqlite3.Row              # filas accesibles por nombre
    return conexion


def _sentencias(esquema):
    return [parte.strip() for parte in esquema.split(";") if parte.strip()]


def crear_tablas(conexion):
    if es_postgres(conexion):
        with conexion as conn:
            for sentencia in _sentencias(ESQUEMA_POSTGRES):
                conn.execute(sentencia)
    else:
        conexion.executescript(ESQUEMA_SQLITE)
        conexion.commit()


if __name__ == "__main__":
    with obtener_conexion() as conn:
        crear_tablas(conn)
        destino = "PostgreSQL (DATABASE_URL)" if es_postgres(conn) else str(DB_PATH)
    print(f"Base de datos lista en: {destino}")
